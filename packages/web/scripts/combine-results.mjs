/**
 * Merges .regression/<engine>/results.json (from regression.mjs) into packages/web/regression-results.md.
 *   node scripts/combine-results.mjs
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { pkgDir } from "./harness.mjs";

const engines = ["svg", "remotion"].filter((e) => existsSync(join(pkgDir, ".regression", e, "results.json")));
const runs = Object.fromEntries(engines.map((e) => [e, JSON.parse(readFileSync(join(pkgDir, ".regression", e, "results.json"), "utf8"))]));
const pct = (x) => (x === undefined ? "-" : `${(x * 100).toFixed(2)}%`);
const first = runs[engines[0]];
const byLook = new Map();
for (const e of engines) for (const r of runs[e].results) byLook.set(r.number, { ...(byLook.get(r.number) ?? { number: r.number, id: r.id, template: r.template }), [e]: r });
const rows = [...byLook.values()].sort((a, b) => (b.svg?.shift ?? 0) - (a.svg?.shift ?? 0) || (b.remotion?.shift ?? 0) - (a.remotion?.shift ?? 0));
const stat = (e) => {
  const rs = runs[e].results;
  const worst = rs.reduce((a, b) => (b.shift > a.shift ? b : a));
  const worstC = rs.reduce((a, b) => (b.coarse > a.coarse ? b : a));
  const sorted = rs.map((r) => r.shift).sort((a, b) => a - b);
  return `| \`${e}\` | ${rs.length} | ${pct(sorted[Math.floor(sorted.length / 2)])} | ${pct(worst.shift)} (#${worst.number} ${worst.id}) | ${pct(worstC.coarse)} (#${worstC.number}) | ${rs.filter((r) => r.shift <= 0.01).length} | ${runs[e].failed.length ? runs[e].failed.join(", ") : "none"} | ${runs[e].webMsPerFrame} ms |`;
};
const md = [
  "# captionseasy-web visual regression results",
  "",
  `Generated by \`node scripts/regression.mjs --engine <svg|remotion>\` + \`node scripts/combine-results.mjs\` on ${first.generatedAt.slice(0, 10)}.`,
  "",
  "## Setup",
  "",
  `- Every gallery look × ${first.times.length} moments (${first.times.join(", ")} ms) at ${first.size}, ${first.fps} fps, on the sample transcript.`,
  "- Each moment is drawn twice:",
  "  - by captionseasy-web on a canvas, in headless Chrome",
  "  - by Remotion's server renderer (`renderStill` of the same `CaptionsOverlay` composition, chrome-headless-shell)",
  "- **off** (the pass metric, a pixel tolerance): the share of caption pixels where no pixel within ±1 px in the other image is within 48/255 (premultiplied RGBA, checked both ways). It forgives sub-pixel text placement but not wrong colours or missing or extra elements.",
  "- **coarse**: the share of caption-covered 4×4 blocks whose mean colour differs by > 32/255.",
  "- **aa**: the share of caption pixels differing by > 48/255 at the same position. This includes glyph anti-aliasing.",
  "- Each look is scored by its worst moment. The thresholds are in `test/regression-thresholds.json`: svg ≤ 2% per look (3D flip #123 ≤ 4%, rotated labels #21 ≤ 3%); the remotion engine is informational (no limit).",
  "",
  "## Summary",
  "",
  "| engine | looks | median off | worst off | worst coarse | looks ≤ 1% off | failed | ms/frame* |",
  "| --- | ---: | ---: | ---: | ---: | ---: | --- | ---: |",
  ...engines.map(stat),
  "",
  "\\* Headless Chrome with a software GPU, including PNG encoding. The first draw of a props object also mounts the captions and embeds the fonts.",
  "",
  "## Per look",
  "",
  `| # | look | template | ${engines.map((e) => `${e} off | ${e} coarse | ${e} aa`).join(" | ")} |`,
  `| ---: | --- | --- | ${engines.map(() => "---: | ---: | ---:").join(" | ")} |`,
  ...rows.map((r) => `| ${r.number} | ${r.id} | ${r.template} | ${engines.map((e) => `${pct(r[e]?.shift)}${r[e] && !r[e].pass ? " FAIL" : ""} | ${pct(r[e]?.coarse)} | ${pct(r[e]?.mismatch)}`).join(" | ")} |`),
  "",
].join("\n");
writeFileSync(join(pkgDir, "regression-results.md"), md);
console.log(`wrote regression-results.md (${engines.join(", ")})`);
