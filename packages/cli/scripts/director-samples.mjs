/**
 * The caption director on the three sample transcripts (test/__fixtures__/director-samples.json), as Markdown:
 *   node packages/cli/scripts/director-samples.mjs > packages/cli/docs/director-samples.md
 * Needs packages/cli/dist built.
 */
import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { directCaptions } from "../dist/index.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const samples = JSON.parse(readFileSync(join(here, "..", "test", "__fixtures__", "director-samples.json"), "utf8"));
const out = ["# Caption director: sample output", "", "Generated by `node packages/cli/scripts/director-samples.mjs` from `test/__fixtures__/director-samples.json`.", ""];
for (const s of samples) {
  const r = directCaptions(s.input);
  const key = new Set(r.keyWords.map((k) => k.index));
  const { words: _w, ...rest } = s.input;
  out.push(`## ${s.name}`, "", "Input: `" + JSON.stringify(rest) + "`", "");
  out.push("> " + s.input.words.map((w, i) => (key.has(i) ? `**${w.text}**` : w.text)).join(" "), "");
  out.push(`- **Look:** #${r.look.number} ${r.look.name}`, `- **Words per card:** ${r.wordsPerCard}`, `- **Key words:** ${r.keyWords.map((k) => `${k.text} (${k.role})`).join(", ")}`, `- **Position:** y ${r.position.y} (${r.position.band} band, ${Math.round(r.position.y * 1920)} px of 1920)`, "");
  out.push("Why:", ...r.reasons.map((x) => `- ${x}`), "");
  out.push("| taste rule | ok | detail |", "| --- | --- | --- |", ...r.checks.map((c) => `| ${c.rule} | ${c.ok ? "yes" : "**no**"} | ${c.detail} |`), "");
  if (r.warnings.length) out.push("Warnings:", ...r.warnings.map((x) => `- ${x}`), "");
  const { words, ...args } = r.args;
  out.push("<details><summary>buildCaptions arguments (words omitted)</summary>", "", "```json", JSON.stringify({ ...args, words: `[${words.length} words]` }, null, 2), "```", "</details>", "");
}
console.log(out.join("\n"));
