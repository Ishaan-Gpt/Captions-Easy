/**
 * Regenerates the "Choosing a look" table in README.md from the look guide, so the docs never drift from the data.
 *
 *   npx tsx scripts/guide-table.ts           rewrite README.md
 *   npx tsx scripts/guide-table.ts --check   exit 1 if README.md is out of date (also covered by the tests)
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { describeLook, listLooks } from "../src/looks";

export const START = "<!-- looks-guide:start (generated by scripts/guide-table.ts; do not edit) -->";
export const END = "<!-- looks-guide:end -->";
export const README = join(dirname(fileURLToPath(import.meta.url)), "..", "README.md");

const cell = (s: string) => s.replace(/\|/g, "\\|");

export function guideTable(): string {
  const rows = listLooks()
    .slice()
    .sort((a, b) => a.number - b.number)
    .map((l) => {
      const g = describeLook(l.id).guide!;
      const q = g.quality ? `${g.quality.tier} ${g.quality.score}` : "new (unrated)";
      return `| ${l.number} | ${cell(l.name)} | ${g.bestFor.slice(0, 3).join(", ")} | ${g.energy} | ${g.tone.join(", ")} | ${q} |`;
    });
  return [START, "", "| # | Look | Best for | Energy (1-5) | Tone | Quality |", "| ---: | --- | --- | :---: | --- | --- |", ...rows, "", END].join("\n");
}

export function withTable(readme: string): string {
  const a = readme.indexOf(START);
  const b = readme.indexOf(END);
  if (a < 0 || b < a) throw new Error(`README.md needs the markers:\n${START}\n${END}`);
  const eol = readme.includes("\r\n") ? "\r\n" : "\n";
  return readme.slice(0, a) + guideTable().replace(/\n/g, eol) + readme.slice(b + END.length);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const now = readFileSync(README, "utf8");
  const next = withTable(now);
  if (process.argv.includes("--check")) {
    if (now !== next) {
      console.error("README.md look table is out of date: run `npx tsx scripts/guide-table.ts`");
      process.exit(1);
    }
    console.log("README.md look table is up to date");
  } else {
    writeFileSync(README, next);
    console.log(`README.md: wrote the table for ${listLooks().length} looks`);
  }
}
