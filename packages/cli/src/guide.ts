/** The full card for a look id (undefined for retired looks), with the 0.2.0 metadata derived in meta.ts. */
export function guideFor(id: string, wordsPerCard: number): LookGuide | undefined {
  const g = GUIDE[id];
  const look = getLook(id);
  if (!g || !look) return undefined;
  const { summary, bestFor, avoidFor, energy, tone, footage, pace, platforms, usage } = g;
  const { scripts, complexScriptSafe } = scriptsFor(look);
  const { pairsWith, avoidWith } = pairsFor(id);
  return {
    summary, energy, tone, bestFor, avoidFor, footage, pace, wordsPerCard, platforms, ...(QUALITY[id] ? { quality: QUALITY[id] } : {}), usage,
    mood: moodOf(g), formality: formalityOf(g), suits: suitsOf(g), scripts, complexScriptSafe, pairsWith, avoidWith,
  };
}

/** The compact card listLooks carries. */
export function briefFor(id: string): LookGuideBrief | undefined {
  const g = GUIDE[id];
  return g ? { summary: g.summary, energy: g.energy, tone: g.tone, bestFor: g.bestFor } : undefined;
}
